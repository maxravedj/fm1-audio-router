"""Render a tiny device self-check from run_bt_ldac.py's trusted fixtures.

Generate only on demand: python3 src/tests/make_ldac_probe.py > build/ldac-probe.h
The committed vectors are independently decoded by ldac_probe_reference.c.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def hash_channel(pcm, channel):
    h = 2166136261
    for i in range(channel*3, len(pcm), 6):
        sample = int.from_bytes(pcm[i:i+3], 'little', signed=True)
        h = ((h ^ (sample & 0xffffffff))*16777619) & 0xffffffff
    return h

print('/* SPDX-License-Identifier: MPL-2.0 */')
print('/* Generated by src/tests/make_ldac_probe.py from the pinned upstream')
print(' * encoder/oracle: first two tone frames after eight silent frames.')
print(' * First frame primes overlap; second-frame channel hashes are checked.')
print(' * Never mixed into audio; CPU1 verifies both channels before live decode. */')
print('struct ldac_probe_vector { uint8_t frames[2][330]; uint32_t hash[2]; };')
print('static const struct ldac_probe_vector ldac_probe_vectors[2] = {')
for rate in (44100, 48000):
    data = (ROOT/f'build/tests/ldac/{rate}-0.bin').read_bytes()
    records = []
    at = 0
    for i in range(10):
        n = int.from_bytes(data[at:at+2], 'little');at += 2
        frame, pcm = data[at:at+n], data[at+n:at+n+768];at += n+768
        assert n == 330 and len(pcm) == 768
        if i < 8:
            assert not any(pcm), 'initial transform overlap must be silent'
        else:
            records.append((frame, pcm))
    print('    { /*',rate,'Hz */ {')
    for frame, pcm in records:
        print('        {')
        for i in range(0, len(frame), 16):
            print('            '+','.join(f'0x{b:02x}' for b in frame[i:i+16])+',')
        print('        },')
    pcm = records[-1][1]
    print('    }, { '+', '.join(f'0x{hash_channel(pcm,ch):08x}u' for ch in (0,1))+' } },')
print('};')
