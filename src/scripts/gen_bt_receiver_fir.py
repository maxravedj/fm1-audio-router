"""Generate the receiver's DC-normalized Q15 Blackman sinc fractional delays."""
from pathlib import Path
import math
out = Path(__file__).resolve().parents[1] / 'bt/br/bt_receiver_fir.h'
text = '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by scripts/gen_bt_receiver_fir.py; Q15, 96 taps/65 phases (64 fractional intervals). */\n'
for name, cutoff in [('BTR_FIR_44', .49), ('BTR_FIR_48', .445)]:
    rows=[]
    for phase in range(65):
        taps=[]
        for k in range(96):
            x=k-(47+phase/64)
            a=2*cutoff*x
            sinc=1 if abs(a)<1e-12 else math.sin(math.pi*a)/(math.pi*a)
            window=.42-.5*math.cos(2*math.pi*k/95)+.08*math.cos(4*math.pi*k/95)
            taps.append(2*cutoff*sinc*window)
        total=sum(taps)
        q=[round(v/total*32768) for v in taps]
        q[47]+=32768-sum(q)
        rows.append('{'+','.join(map(str,q))+'}')
    text+='static const int16_t '+name+'[65][96]={\n'+',\n'.join(rows)+'\n};\n'
out.write_text(text)
