"""Generate the gateway's monotone cubic MASTER gain coefficients; no device IO."""
import argparse
from pathlib import Path

POINTS = (0.0, 0.1, 0.5, 0.75, 1.0)
LEVELS_DB = (None, -60.0, -30.0, -15.0, 0.0)
OUTPUT = Path(__file__).resolve().parents[1] / 'apps/fm1-audio-gateway/gain.h'

def coefficients():
    y = [0.0 if db is None else 10.0**(db/20.0) for db in LEVELS_DB]
    h = [b-a for a,b in zip(POINTS, POINTS[1:])]
    secant = [(b-a)/step for a,b,step in zip(y,y[1:],h)]
    slope = [0.0]*len(y)
    for i in range(1, len(y)-1):
        w1, w2 = 2*h[i]+h[i-1], h[i]+2*h[i-1]
        slope[i] = (w1+w2)/(w1/secant[i-1]+w2/secant[i])
    def endpoint(a,b,da,db):
        value=((2*a+b)*da-a*db)/(a+b)
        return min(3*da,max(0.0,value))
    slope[0]=endpoint(h[0],h[1],secant[0],secant[1])
    slope[-1]=endpoint(h[-1],h[-2],secant[-1],secant[-2])
    for i,step in enumerate(h):
        delta=y[i+1]-y[i];left=step*slope[i];right=step*slope[i+1]
        yield (POINTS[i],1.0/step,left+right-2*delta,3*delta-2*left-right,left,y[i])

def render():
    def literal(x):
        s=format(x,'.10g')
        return (s if '.' in s or 'e' in s else s+'.0')+'f'
    rows='\n'.join('        {'+', '.join(map(literal,row))+'},' for row in coefficients())
    return '''/* SPDX-License-Identifier: MPL-2.0
 * Generated by src/scripts/generate_master_curve.py. MASTER is a monotone
 * cubic Hermite gain curve: 0% silence, 10% -60, 50% -30, 75% -15, 100% 0 dB.
 * Slopes use weighted harmonic means and bounded endpoints (PCHIP).
 * Audio gain evaluates once per block without pow/log, allocation or a sample loop.
 * Faders retain -100..0 dB plus a distinct OFF position. */
#define GATEWAY_GAIN_MIN (-1000)
#define GATEWAY_GAIN_OFF (GATEWAY_GAIN_MIN-1)
float app_master_gain(uint32_t position)
{
    /* start, inverse width, cubic coefficients a/b/c/d in normalized t */
    static const float curve[4][6]={
'''+rows+'''
    };
    if(!position)return 0.0f;
    if(position>=4096u)return 4096.0f;
    float x=(float)position*(1.0f/4096.0f);
    unsigned i=x<0.1f?0:x<0.5f?1:x<0.75f?2:3;
    const float *c=curve[i];float t=(x-c[0])*c[1];
    return (((c[2]*t+c[3])*t+c[4])*t+c[5])*4096.0f;
}
static int gateway_master_db(uint32_t position)
{
    if(!position)return GATEWAY_GAIN_OFF;
    if(position>=4096u)return 0;
    /* Mixer foreground only: display the same gain as the actual audio tap,
     * including finite MASTER levels below -100 dB. */
    float gain=app_master_gain(position)*(1.0f/4096.0f);
    return (int)(60.20599913f*fm_log2f(gain)-0.5f);
}
'''

def plot_formula():
    rows=[]
    for i,(start,scale,a,b,c,d) in enumerate(coefficients()):
        t='x' if start==0 else f'(x-{start:g})'
        parts=[(a*scale**3,t+'^3'),(b*scale**2,t+'^2'),(c*scale,t),(d,'')]
        expression=''
        for value,power in parts:
            if not value:continue
            sign='-' if value<0 else '+' if expression else ''
            expression+=sign+format(abs(value),'.12g')+('*'+power if power else '')
        end='<=' if i==3 else '<'
        rows.append(f'  {start:g} <= x {end} {POINTS[i+1]:g}: {expression}')
    return 'G(x) = {\n'+',\n'.join(rows)+'\n}\nD(p) = 20*log10(G(p/100))\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--formula',action='store_true',help='print a plotting formula, p in percent')
    args=parser.parse_args();content=render()
    if args.formula:
        print(plot_formula(),end='')
    elif args.check:
        if OUTPUT.read_text()!=content:raise SystemExit('MASTER curve header differs from generator')
        print('PASS: MASTER curve header matches the control points and monotone cubic generator')
    else:
        OUTPUT.write_text(content)
        print('Generated', OUTPUT)
if __name__=='__main__':main()
